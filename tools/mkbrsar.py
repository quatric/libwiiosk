#!/usr/bin/env python3
"""
mkbrsar.py -- embed the Wii keyboard's sound archive into wiiosk

    python3 tools/mkbrsar.py wiiSoftwareKeyboardSound.brsar > source/osk_sound_data.c

The keyboard's sound effects are played from the archive itself (source/osk_brsar.c renders them
with the sequencer and synthesizer of source/osk_seqsynth.c). Its instrument bank holds waves
that none of the 19 sounds use; their samples are zeroed (everything else, so every offset,
stays as it is) before the file is packed by tools/rcpack.py (its byte model), which turns the
zeros into almost nothing.
"""

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rcpack

# waves of the bank (RBNK) that no sound uses
UNUSED_WAVES = {1, 19}


def u32(d, o):
	return struct.unpack_from(">I", d, o)[0]


def u16(d, o):
	return struct.unpack_from(">H", d, o)[0]


def ref(d, o):
	return d[o], d[o + 1], u32(d, o + 4)


def strip(d):
	d = bytearray(d)
	assert d[:4] == b"RSAR"
	base = u32(d, 0x18) + 8
	groups = base + ref(d, base + 4 * 8)[2]
	for g in range(u32(d, groups)):
		go = base + ref(d, groups + 4 + g * 8)[2]
		data, wave = u32(d, go + 16), u32(d, go + 24)
		items = base + ref(d, go + 32)[2]
		for i in range(u32(d, items)):
			io = base + ref(d, items + 4 + i * 8)[2]
			off = data + u32(d, io + 4)
			wblk = wave + u32(d, io + 12)
			if d[off:off + 4] != b"RBNK":
				continue
			for k in range(u16(d, off + 0xE)):
				so = off + u32(d, off + 0x10 + k * 8)
				if d[so:so + 4] != b"WAVE":
					continue
				for w in range(u32(d, so + 8)):
					if w not in UNUSED_WAVES:
						continue
					wi = so + 8 + u32(d, so + 12 + w * 8 + 4)
					fmt, ch, end = d[wi], d[wi + 2], u32(d, wi + 12)
					loc, table = u32(d, wi + 20), wi + u32(d, wi + 16)
					size = (end + 15) // 16 * 8 if fmt == 2 else end * 2 if fmt == 1 else end
					for c in range(ch):
						start = wblk + loc + u32(d, wi + u32(d, table + c * 4))
						d[start:start + size] = bytes(size)
	return bytes(d)


def main():
	if len(sys.argv) != 2:
		sys.exit(__doc__)
	raw = strip(open(sys.argv[1], "rb").read())
	packed = rcpack.pack(raw, rcpack.MODEL_BYTES)
	assert rcpack.unpack(packed) == raw
	print("/* Generated by tools/mkbrsar.py from wiiSoftwareKeyboardSound.brsar.")
	print("   Do not edit. %d bytes of sound archive, packed. */" % len(raw))
	print('#include "osk_internal.h"')
	print()
	print(rcpack.c_array("osk_sound_packed", packed))
	print("const unsigned osk_sound_packed_size = sizeof(osk_sound_packed);")
	print("%d bytes packed" % len(packed), file=sys.stderr)


if __name__ == "__main__":
	main()
