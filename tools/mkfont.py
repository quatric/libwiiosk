#!/usr/bin/env python3
"""Generate source/osk_font_data.c, the anti-aliased glyph atlas used by wiiosk.

    python3 tools/mkfont.py path/to/FOT-RodinNTLGPro-DB.otf > source/osk_font_data.c

Any TrueType/OpenType font works; the atlas header names the font it was
rendered from. The 4-bit atlas is packed by tools/rcpack.py (its image
model) and unpacked once at startup by osk_font_unpack() in
source/osk_text.c. Requires Pillow.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rcpack

EM = 31			# pixel size the atlas is rendered at: cap height just above
			# the largest on-screen text, so glyphs are only ever scaled down
SS = 4			# supersampling factor
PAD = 2			# empty texels around every glyph (bilinear filtering)
ATLAS_W = 512

CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x152, 0x153, 0x20AC]


def main():
	font = ImageFont.truetype(sys.argv[1], EM * SS)
	name = ' '.join(font.getname())
	ascent, descent = font.getmetrics()
	hb = font.getmask('H').getbbox()
	cap = (hb[3] - hb[1]) / SS

	glyphs = []
	for cp in CODEPOINTS:
		ch = chr(cp)
		adv = font.getlength(ch) / SS
		# getbbox() is not tight, so measure the rendered ink instead
		size = EM * SS * 3
		big = Image.new('L', (size, size), 0)
		ImageDraw.Draw(big).text((EM * SS, EM * SS * 2), ch, font=font, fill=255, anchor='ls')
		ink = big.getbbox()
		if cp in (0x20, 0xA0) or not ink:
			glyphs.append((cp, None, 0, 0, adv))
			continue
		# pixel-aligned box in final resolution, origin on the baseline
		l, t = ink[0] - EM * SS, ink[1] - EM * SS * 2
		r, b = ink[2] - EM * SS, ink[3] - EM * SS * 2
		x0, y0 = l // SS, t // SS
		x1, y1 = -(-r // SS), -(-b // SS)
		w, h = x1 - x0, y1 - y0
		img = big.crop((EM * SS + x0 * SS, EM * SS * 2 + y0 * SS,
				EM * SS + x1 * SS, EM * SS * 2 + y1 * SS))
		img = img.resize((w, h), Image.BOX)
		glyphs.append((cp, img, x0, -y0, adv))

	# shelf packing, tallest glyphs first so shelves waste little height
	x = y = shelf = 0
	placed = []
	for cp, img, left, top, adv in sorted(glyphs, key=lambda g: -g[1].size[1] if g[1] else 0):
		if img is None:
			placed.append((cp, 0, 0, 0, 0, 0, 0, adv))
			continue
		w, h = img.size
		if x + w + 2 * PAD > ATLAS_W:
			x, y, shelf = 0, y + shelf, 0
		placed.append((cp, x + PAD, y + PAD, w, h, left, top, adv, img))
		x += w + 2 * PAD
		shelf = max(shelf, h + 2 * PAD)
	atlas_h = y + shelf
	atlas_h = (atlas_h + 7) & ~7
	placed.sort(key=lambda p: p[0])

	atlas = Image.new('L', (ATLAS_W, atlas_h), 0)
	for p in placed:
		if len(p) == 9:
			atlas.paste(p[8], (p[1], p[2]))
	px = atlas.load()

	out = sys.stdout
	out.write('/* Generated by tools/mkfont.py from %s. Do not edit. */\n' % name)
	out.write('#include "osk_internal.h"\n\n')
	out.write('const unsigned osk_font_atlas_w = %d, osk_font_atlas_h = %d;\n' % (ATLAS_W, atlas_h))
	out.write('const float osk_font_em = %d.0f, osk_font_cap = %.3ff, osk_font_ascent = %.3ff, osk_font_descent = %.3ff;\n\n'
		  % (EM, cap, ascent / SS, descent / SS))
	data = []
	for yy in range(atlas_h):
		for xx in range(0, ATLAS_W, 2):
			a = (px[xx, yy] * 15 + 127) // 255
			b = (px[xx + 1, yy] * 15 + 127) // 255
			data.append(a << 4 | b)
	packed = rcpack.pack(data, rcpack.MODEL_IMAGE, ATLAS_W)
	out.write('/* 4-bit coverage, two texels per byte, left texel in the high nibble\n'
		  '   (%d bytes unpacked), packed by tools/rcpack.py */\n' % (ATLAS_W * atlas_h // 2))
	out.write(rcpack.c_array('osk_font_atlas_packed', packed) + '\n')
	out.write('const unsigned osk_font_atlas_packed_size = sizeof(osk_font_atlas_packed);\n\n')
	out.write('const osk_glyph osk_font_glyphs[%d] = {\n' % len(placed))
	for p in placed:
		cp, gx, gy, w, h, left, top, adv = p[:8]
		out.write('\t{ 0x%04x, %3d, %3d, %2d, %2d, %3d, %3d, %4d },\n' % (cp, gx, gy, w, h, left, top, round(adv * 16)))
	out.write('};\n')
	out.write('const unsigned osk_font_nglyphs = %d;\n' % len(placed))


if __name__ == '__main__':
	main()
