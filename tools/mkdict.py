#!/usr/bin/env python3
"""
mkdict.py -- turn eZiText dictionaries into wiiosk dictionary objects

    python3 tools/mkdict.py <data dir> <out dir>

<data dir> holds the eZTSystem<LANG>.zsd and eZTNintendo<LANG>.znd files
(the "data" folder of eZiTextTools). One C file per language is written
to <out dir>, each defining a `const osk_dictionary osk_dict_<id>`.
The files are separate objects in libwiiosk.a, so an app only links the
languages it references.

The .zsd is cut down to the two records wiiosk reads: record 0 (the
character set and the word graph) and record 4 (the blocklist). The
result is still a valid .zsd: a 4 byte header, a table of contents of
6 byte (BE24 size, BE24 offset) records from offset 4, record 0 directly
after the table. The .znd follows it unchanged, and both are packed
together by tools/rcpack.py (its dictionary model).
"""

import os
import struct
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rcpack

# id, file suffix, display name (shown on the prediction key)
LANGUAGES = [
	("en_us", "ENAM", "English"),
	("en_gb", "ENUK", "English (UK)"),
	("de", "DE", "Deutsch"),
	("fr", "FREU", "Fran\u00e7ais"),
	("fr_ca", "FRCA", "Fran\u00e7ais (CA)"),
	("es", "ESEU", "Espa\u00f1ol"),
	("es_la", "ESSA", "Espa\u00f1ol (LA)"),
	("it", "IT", "Italiano"),
	("nl", "NL", "Nederlands"),
]


def be24(data, off):
	return (data[off] << 16) | (data[off + 1] << 8) | data[off + 2]


def pack24(v):
	return bytes([(v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF])


def records(data):
	base = be24(data, 7)
	out = {}
	i = 0
	while i * 6 + 10 <= base:
		size, off = be24(data, i * 6 + 4), be24(data, i * 6 + 7)
		if size or off:
			out[i] = (off, size)
		i += 1
	return out


def blocklist_bytes(data, off, count):
	cur = off
	for _ in range(count):
		cur += 1 + data[cur]
	return data[off:cur]


def strip_zsd(data):
	rec = records(data)
	off0, size0 = rec[0]
	off4, count4 = rec[4]
	rec0 = data[off0:off0 + size0]
	rec4 = blocklist_bytes(data, off4, count4)

	toc_end = 4 + 5 * 6
	toc = bytearray(5 * 6)
	toc[0:3] = pack24(len(rec0))
	toc[3:6] = pack24(toc_end)
	toc[24:27] = pack24(count4)
	toc[27:30] = pack24(toc_end + len(rec0))
	out = bytes(data[:4]) + bytes(toc) + rec0 + rec4
	assert records(out) == {0: (toc_end, len(rec0)), 4: (toc_end + len(rec0), count4)}
	return out


def c_string(s):
	out = ""
	for b in s.encode("utf-8"):
		out += chr(b) if 0x20 <= b < 0x7F and b not in (0x22, 0x5C) else "\\x%02X\"\"" % b
	return '"' + out + '"'


def main():
	if len(sys.argv) != 3:
		sys.exit(__doc__)
	src, dst = Path(sys.argv[1]), Path(sys.argv[2])
	dst.mkdir(parents=True, exist_ok=True)
	for ident, suffix, name in LANGUAGES:
		zsd = strip_zsd((src / f"eZTSystem{suffix}.zsd").read_bytes())
		znd = (src / f"eZTNintendo{suffix}.znd").read_bytes()
		(count,) = struct.unpack_from(">I", znd, 0)
		packed = rcpack.pack(zsd + znd, rcpack.MODEL_DICT)
		assert rcpack.unpack(packed) == zsd + znd
		text = f"""/* Generated by tools/mkdict.py from eZTSystem{suffix}.zsd and
   eZTNintendo{suffix}.znd ({count} extra words). Do not edit. */
#include "wiiosk.h"

static {rcpack.c_array("packed", packed)}

const osk_dictionary osk_dict_{ident} = {{
	{c_string(name)}, NULL, {len(zsd)}, NULL, {len(znd)}, packed, sizeof(packed)
}};
"""
		(dst / f"osk_dict_{ident}.c").write_text(text)
		print(f"osk_dict_{ident}: {len(zsd) + len(znd)} -> {len(packed)} bytes", file=sys.stderr)


if __name__ == "__main__":
	main()
