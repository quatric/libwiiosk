#!/usr/bin/env python3
"""
mktex.py -- generate source/osk_tex_data.c from the keyboard's textures

    python3 tools/mktex.py <softKeyboard_external dir> > source/osk_tex_data.c

<softKeyboard_external dir> is the data folder of the Software Keyboard
SDK package (it holds texture/tex_picture/...). Each texture is converted
to the GX format its layout uses (I4, IA4, IA8 or RGB5A3), so the colors
are exactly what the system keyboard samples. The channels are stored as
4-bit planes (8-bit channels as a high and a low plane), stacked into one
image PLANE_W pixels wide and packed by tools/rcpack.py (its image model).
osk_gfx.c turns them back into RGBA images.
"""

import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rcpack

PLANE_W = 200

# osk_tex, file below texture/tex_picture, GX format, transform
TEXTURES = [
	("OSK_TEX_WHITE", "common/P_common_square_8x8_00", "I4", None),
	("OSK_TEX_STRIPES", "common/P_common_squareBorder_8x8_00", "I4", None),
	("OSK_TEX_GLASS_KEY", "common/fs_glassPlate_d", "IA8", None),
	("OSK_TEX_GLASS_WIDE", "common/fs_glassPlate_g", "IA8", None),
	("OSK_TEX_GLASS_SPACE", "common/fs_glassPlate_space", "IA8", None),
	("OSK_TEX_PLATE", "common/fs_glassPlate_f", "IA8", None),
	("OSK_TEX_PILL", "toobar/fs_ComBtn_c", "RGB5A3", None),
	("OSK_TEX_TOOL", "toobar/fs_toolButton_a", "IA8", None),
	("OSK_TEX_ICON_QWERTY", "toobar/fs_qwertyIcon_a", "IA4", None),
	("OSK_TEX_ICON_NUMPAD", "toobar/fs_cellPhoneIcon_a", "IA4", None),
	("OSK_TEX_ICON_BACK", "common/fs_VK_backspace_a", "I4", None),
	("OSK_TEX_ICON_ENTER", "common/fs_VK_lineFeed_a", "I4", None),
	("OSK_TEX_ICON_SHIFT", "common/fs_VK_shiftCaps_a", "IA4", None),
	("OSK_TEX_ARROW", "common/fs_scrollAllow_a", "IA4", None),
	("OSK_TEX_FRAME_THICK", "common/fs_windowParts_a", "IA4", None),
	("OSK_TEX_FRAME_THIN", "common/fs_windowParts_g", "IA4", None),
	("OSK_TEX_BOOK_OPEN", "precitionIcon/fs_predictionIconON_a", "IA4", None),
	("OSK_TEX_BOOK_CLOSED", "precitionIcon/fs_predictionIconOFF_a", "IA4", None),
	# the candidate bar turns the scroll arrow by 90 degrees to point left
	("OSK_TEX_SCROLL", "common/fs_scrollAllow_a", "IA4", Image.Transpose.ROTATE_90),
	("OSK_TEX_ROUND", "common/fs_roundPlate_a", "IA4", None),
]

# planes per format: channel, shift (4 = high nibble, 0 = low nibble)
PLANES = {
	"I4": [(0, 4)],
	"IA4": [(0, 4), (3, 4)],
	"IA8": [(0, 4), (0, 0), (3, 4), (3, 0)],
	"RGBA": [(c, s) for c in range(4) for s in (4, 0)],
}
FORMAT_ID = {"I4": 1, "IA4": 2, "IA8": 3, "RGBA": 4}


def quant(v, bits):
	n = (1 << bits) - 1
	q = (v * n + 127) // 255
	return (q * 255 + n // 2) // n


def convert(im, fmt):
	"""texels as (r, g, b, a) after the GX format's quantization; I
	formats hold the intensity in r, g and b"""
	px = im.convert("RGBA").tobytes()
	has_alpha = im.mode in ("RGBA", "LA")
	out = []
	for k in range(0, len(px), 4):
		r, g, b, a = px[k:k + 4]
		i = (r * 299 + g * 587 + b * 114 + 500) // 1000
		if fmt == "I4":
			i = quant(i, 4)
			out.append((i, i, i, i))
		elif fmt == "IA4":
			out.append((quant(i, 4),) * 3 + (quant(a, 4) if has_alpha else 255,))
		elif fmt == "IA8":
			out.append((i, i, i, a if has_alpha else 255))
		else:	# RGB5A3: opaque RGB555, else ARGB3444
			if a >= 0xE0:
				out.append((quant(r, 5), quant(g, 5), quant(b, 5), 255))
			else:
				out.append((quant(r, 4), quant(g, 4), quant(b, 4), quant(a, 3)))
	return out


def main():
	if len(sys.argv) != 2:
		sys.exit(__doc__)
	base = os.path.join(sys.argv[1], "texture", "tex_picture")
	rows = []		# nibble rows, PLANE_W wide
	infos = []
	for name, path, fmt, transform in TEXTURES:
		im = Image.open(os.path.join(base, path + ".tga"))
		if transform is not None:
			im = im.transpose(transform)
		w, h = im.size
		assert w <= PLANE_W, path
		store = "RGBA" if fmt == "RGB5A3" else fmt
		texels = convert(im, fmt)
		infos.append((name, os.path.basename(path), fmt, w, h, store, len(rows)))
		for ch, shift in PLANES[store]:
			for y in range(h):
				rows.append([(texels[y * w + x][ch] >> shift) & 15 for x in range(w)] + [0] * (PLANE_W - w))
	raw = bytearray()
	for row in rows:
		for x in range(0, PLANE_W, 2):
			raw.append(row[x] << 4 | row[x + 1])
	packed = rcpack.pack(raw, rcpack.MODEL_IMAGE, PLANE_W)
	assert rcpack.unpack(packed) == bytes(raw)

	print("/* Generated by tools/mktex.py from the Software Keyboard SDK textures.")
	print("   Do not edit. 4-bit planes, packed; see tools/mktex.py. */")
	print('#include "osk_internal.h"')
	print()
	print("const unsigned osk_tex_plane_w = %d;" % PLANE_W)
	print()
	print("const osk_tex_source osk_tex_sources[OSK_TEX_IMAGES] = {")
	for name, src, fmt, w, h, store, row in infos:
		print("\t[%s] = { %d, %d, %d, %d },\t/* %s, %s */" % (name, w, h, FORMAT_ID[store], row, src, fmt))
	print("};")
	print()
	print(rcpack.c_array("osk_tex_packed", packed, " /* %d bytes unpacked */" % len(raw)))
	print("const unsigned osk_tex_packed_size = sizeof(osk_tex_packed);")
	print("texture planes: %d -> %d bytes" % (len(raw), len(packed)), file=sys.stderr)


if __name__ == "__main__":
	main()
